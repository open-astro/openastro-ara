/// §61 settings registry. Single source of truth for every settable field
/// across all panels. Used for:
/// 1. Search index (Command Palette)
/// 2. Inline edit rendering
/// 3. Cross-linking hints
/// 4. Mechanical enforcement gate (COMMIT-PR-RULES.md)
library;

enum SettingTypeKind {
  bool,
  intRange,
  doubleRange,
  enumValue,
  string,
  duration,
  color,
  keyboardShortcut,
  path,
  complex,
}

class SettingType {
  final SettingTypeKind kind;
  final num? min;
  final num? max;
  final num? step;
  final List<String>? enumValues;

  const SettingType.bool()
    : kind = SettingTypeKind.bool,
      min = null,
      max = null,
      step = null,
      enumValues = null;
  const SettingType.intRange({required int min, required int max})
    : kind = SettingTypeKind.intRange,
      // ignore: prefer_initializing_formals
      min = min,
      // ignore: prefer_initializing_formals
      max = max,
      step = 1,
      enumValues = null;
  const SettingType.doubleRange({
    required double min,
    required double max,
    double step = 0.1,
  }) : kind = SettingTypeKind.doubleRange,
       // ignore: prefer_initializing_formals
       min = min,
       // ignore: prefer_initializing_formals
       max = max,
       // ignore: prefer_initializing_formals
       step = step,
       enumValues = null;
  const SettingType.enumValue(List<String> values)
    : kind = SettingTypeKind.enumValue,
      min = null,
      max = null,
      step = null,
      enumValues = values;
  const SettingType.string()
    : kind = SettingTypeKind.string,
      min = null,
      max = null,
      step = null,
      enumValues = null;
  const SettingType.duration()
    : kind = SettingTypeKind.duration,
      min = null,
      max = null,
      step = null,
      enumValues = null;
  const SettingType.path()
    : kind = SettingTypeKind.path,
      min = null,
      max = null,
      step = null,
      enumValues = null;
  const SettingType.complex()
    : kind = SettingTypeKind.complex,
      min = null,
      max = null,
      step = null,
      enumValues = null;
}

/// #1544 — [simple] entries are the few a user is expected to touch (and
/// Simple Mode itself offers). With the one global Advanced toggle off, the
/// Autofocus panel shows only its [simple] rows and any row a search hit
/// opens; the other panels show every row.
enum SettingTier { simple, advanced }

class Setting {
  final String id;
  final String label;
  final String description;
  final List<String> keywords;
  final List<String> path;
  final SettingType type;
  final dynamic defaultValue;
  final String? profilePath;
  final List<String> relatedSettings;

  /// #1544 — see [SettingTier].
  final SettingTier tier;

  /// #1544 — what computes the value when the user does not override it
  /// ("Automatic step size: ..."); null when nothing derives it. Registry
  /// metadata: the panel shows the derived value itself, not this text.
  final String? derivedBy;

  const Setting({
    required this.id,
    required this.label,
    required this.description,
    required this.keywords,
    required this.path,
    required this.type,
    required this.defaultValue,
    this.profilePath,
    this.relatedSettings = const <String>[],
    required this.tier,
    this.derivedBy,
  });
}

