using NUnit.Framework;
using OpenAstroAra.Server.Services;
using System;
using System.Diagnostics.CodeAnalysis;
using System.Linq;

namespace OpenAstroAra.Test {

    /// <summary>
    /// §45 — the ARA-owned polar-alignment geometry, proven against synthetic skies: pointings
    /// generated by Rodrigues rotation about a KNOWN axis must recover that axis exactly, the
    /// Bennett refraction term must match the almanac anchors, and the alt/az decomposition must
    /// reproduce closed-form meridian cases (independent of the implementation's own formulas).
    /// </summary>
    [TestFixture]
    public class PolarAlignGeometryTest {

        // ── synthetic-sky helpers ────────────────────────────────────────────────────────────

        private static (double X, double Y, double Z) Unit(double raDeg, double decDeg) {
            var ra = raDeg * Math.PI / 180.0;
            var dec = decDeg * Math.PI / 180.0;
            return (Math.Cos(dec) * Math.Cos(ra), Math.Cos(dec) * Math.Sin(ra), Math.Sin(dec));
        }

        private static (double RaDeg, double DecDeg) RaDec((double X, double Y, double Z) v) {
            var ra = Math.Atan2(v.Y, v.X) * 180.0 / Math.PI;
            if (ra < 0) ra += 360.0;
            return (ra, Math.Asin(Math.Clamp(v.Z, -1, 1)) * 180.0 / Math.PI);
        }

        // Rodrigues rotation of v about the unit axis k by angleDeg — the independent generator
        // the fit must invert.
        private static (double X, double Y, double Z) Rotate(
                (double X, double Y, double Z) v, (double X, double Y, double Z) k, double angleDeg) {
            var a = angleDeg * Math.PI / 180.0;
            var cos = Math.Cos(a);
            var sin = Math.Sin(a);
            var cross = (X: k.Y * v.Z - k.Z * v.Y, Y: k.Z * v.X - k.X * v.Z, Z: k.X * v.Y - k.Y * v.X);
            var dot = k.X * v.X + k.Y * v.Y + k.Z * v.Z;
            return (
                v.X * cos + cross.X * sin + k.X * dot * (1 - cos),
                v.Y * cos + cross.Y * sin + k.Y * dot * (1 - cos),
                v.Z * cos + cross.Z * sin + k.Z * dot * (1 - cos));
        }

        private static (double X, double Y, double Z) Cross((double X, double Y, double Z) a, (double X, double Y, double Z) b) =>
            (a.Y * b.Z - a.Z * b.Y, a.Z * b.X - a.X * b.Z, a.X * b.Y - a.Y * b.X);

        private static void AssertFitRecovers(double axisRa, double axisDec, double pointRa,
                double pointDec, double rotationDeg, bool north) {
            var axis = Unit(axisRa, axisDec);
            var p1 = Unit(pointRa, pointDec);
            var p2 = Rotate(p1, axis, rotationDeg);
            var (ra1, dec1) = RaDec(p1);
            var (ra2, dec2) = RaDec(p2);

            var fitted = PolarAlignGeometry.FitAxisTwoPoint(ra1, dec1, ra2, dec2, rotationDeg, north);

            // Compare as an angular separation, not per-component (RA degenerates near the pole).
            var sep = Math.Acos(Math.Clamp(
                Unit(fitted.RaDeg, fitted.DecDeg).X * axis.X
                + Unit(fitted.RaDeg, fitted.DecDeg).Y * axis.Y
                + Unit(fitted.RaDeg, fitted.DecDeg).Z * axis.Z, -1, 1)) * 180.0 / Math.PI;
            Assert.That(sep, Is.LessThan(1e-6),
                $"axis ({axisRa},{axisDec}) Δ={rotationDeg}° must be recovered exactly from noise-free pointings");
        }

        [Test]
        public void Two_point_fit_recovers_a_known_axis_across_geometries() {
            // A slightly-misaligned northern mount (the real use case): axis ~0.5° off the NCP.
            AssertFitRecovers(axisRa: 30, axisDec: 89.5, pointRa: 100, pointDec: 50, rotationDeg: 60, north: true);
            // Smaller + larger commanded rotations.
            AssertFitRecovers(30, 89.5, 100, 50, 30, true);
            AssertFitRecovers(30, 89.5, 100, 50, 90, true);
            // A worse initial alignment (2° off) and a pointing near the equator.
            AssertFitRecovers(210, 88.0, 350, 5, 60, true);
            // Southern hemisphere: axis near the SCP, disambiguated south.
            AssertFitRecovers(120, -89.3, 40, -40, 60, north: false);
        }

        [Test]
        public void Two_point_fit_handles_pointings_more_than_ninety_degrees_from_the_axis() {
            // The review's counterexample: axis at the true NCP, seed star at Dec −30° (θ = 120°
            // — a routine southern-declination choice while aligning north). The cosθ sign is
            // not recoverable from the chord, and the ghost axis line even reproduces the
            // rotation — the nearest-pole disambiguation must still return the NCP, not the
            // ~67°-away ghost the original single-sign construction picked.
            AssertFitRecovers(axisRa: 0, axisDec: 90, pointRa: 0, pointDec: -30, rotationDeg: 60, north: true);
            // The same regime on a realistically misaligned axis, both hemispheres.
            AssertFitRecovers(30, 89.5, 100, -30, 60, true);
            AssertFitRecovers(120, -89.3, 40, 25, 60, north: false);
        }

        [Test]
        public void Two_point_fit_refuses_an_axis_far_from_the_target_pole() {
            // An axis 60° from the pole violates the §45 rough-alignment precondition — the fit
            // must refuse rather than hand the bullseye a number it can't distinguish from the
            // ghost line.
            var axis = Unit(0, 30);
            var p1 = Unit(80, 60);
            var p2 = Rotate(p1, axis, 60);
            var (ra1, dec1) = RaDec(p1);
            var (ra2, dec2) = RaDec(p2);
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.FitAxisTwoPoint(ra1, dec1, ra2, dec2, 60, true));
        }

        [Test]
        public void Two_point_fit_rejects_degenerate_inputs() {
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.FitAxisTwoPoint(100, 50, 100, 50, 60, true),
                "coincident pointings carry no axis information");
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.FitAxisTwoPoint(100, 50, 120, 50, 0, true),
                "a zero rotation is meaningless");
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.FitAxisTwoPoint(100, 50, 120, 50, 180, true),
                "at 180° the short-way chord is ambiguous");
            // Pointings 90° apart cannot come from a 10° rotation — a bad solve must throw, not
            // silently produce a garbage axis the bullseye would chase.
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.FitAxisTwoPoint(0, 0, 90, 0, 10, true));
        }

        [Test]
        public void Bennett_matches_the_almanac_anchors() {
            // Horizon ≈ 34′ (the classic sunrise figure), 45° ≈ 1′, zenith ≈ 0.
            Assert.That(PolarAlignGeometry.BennettRefractionArcmin(0), Is.EqualTo(34.5).Within(0.5));
            Assert.That(PolarAlignGeometry.BennettRefractionArcmin(45), Is.EqualTo(0.96).Within(0.05));
            Assert.That(PolarAlignGeometry.BennettRefractionArcmin(90), Is.EqualTo(0).Within(0.06));
            Assert.Throws<ArgumentOutOfRangeException>(() => PolarAlignGeometry.BennettRefractionArcmin(-1));
        }

        // A fixed instant + site for the alt/az cases; LST enters only through "axis RA = LST"
        // constructions, so the exact value never appears in an expectation.
        private static readonly DateTimeOffset T = new(2026, 12, 21, 22, 0, 0, TimeSpan.Zero);
        private const double Lat = 45.0;
        private const double Lon = 0.0;

        [Test]
        public void An_axis_at_the_true_pole_reads_minus_refraction_in_altitude() {
            // The TRUE pole (dec +90) appears BELOW the refracted target by exactly Bennett(lat):
            // a mount aimed at the true pole still shows a small negative altitude error because
            // the solved sky it was measured against is refraction-lifted.
            var (altErr, azErr) = PolarAlignGeometry.AxisError(0, 90, Lat, Lon, T);
            Assert.That(altErr, Is.EqualTo(-PolarAlignGeometry.BennettRefractionArcmin(Lat)).Within(0.01));
            Assert.That(azErr, Is.EqualTo(0).Within(0.01));
        }

        [Test]
        public void A_meridian_offset_axis_reads_the_closed_form_altitude_error() {
            // Axis on the local meridian (RA = LST → hour angle 0), 10′ below the pole in dec:
            // at upper culmination above the pole, alt = lat + (90 − dec), so the altitude error
            // is +10′ − Bennett(lat). Closed form independent of the implementation's alt/az path.
            var lst = SiteAstrometry.LocalSiderealTimeDeg(T, Lon);
            var (altErr, azErr) = PolarAlignGeometry.AxisError(lst, 90 - 10.0 / 60.0, Lat, Lon, T);
            Assert.That(altErr, Is.EqualTo(10.0 - PolarAlignGeometry.BennettRefractionArcmin(Lat)).Within(0.02));
            Assert.That(azErr, Is.EqualTo(0).Within(0.02));
        }

        [Test]
        public void Azimuth_error_mirrors_across_the_meridian() {
            // An off-meridian axis and its mirror (RA reflected about the LST) must read equal and
            // opposite azimuth errors and identical altitude errors — the knob-direction signs
            // cannot depend on which side of the meridian the measurement happened.
            var lst = SiteAstrometry.LocalSiderealTimeDeg(T, Lon);
            var (altE, azE) = PolarAlignGeometry.AxisError(lst + 40, 89.7, Lat, Lon, T);
            var (altW, azW) = PolarAlignGeometry.AxisError(lst - 40, 89.7, Lat, Lon, T);
            Assert.That(azE, Is.EqualTo(-azW).Within(1e-6));
            Assert.That(altE, Is.EqualTo(altW).Within(1e-6));
            Assert.That(Math.Abs(azE), Is.GreaterThan(1.0), "a 0.3° off-pole axis at ±40° HA has a real az component");
        }

        [Test]
        public void End_to_end_a_synthetic_misalignment_round_trips_through_fit_and_error() {
            // Generate pointings from a KNOWN slightly-misaligned axis, fit it, decompose the
            // error — the whole §45 measurement pipeline on a synthetic sky. The recovered total
            // error must equal the constructed axis-to-apparent-pole separation.
            var lst = SiteAstrometry.LocalSiderealTimeDeg(T, Lon);
            const double offArcmin = 25.0;
            var axisDec = 90 - offArcmin / 60.0;         // 25′ from the true pole, on the meridian
            var axis = Unit(lst, axisDec);
            var p1 = Unit(lst + 80, 40);
            var p2 = Rotate(p1, axis, 60);
            var (ra1, dec1) = RaDec(p1);
            var (ra2, dec2) = RaDec(p2);

            var fitted = PolarAlignGeometry.FitAxisTwoPoint(ra1, dec1, ra2, dec2, 60, true);
            var (altErr, azErr) = PolarAlignGeometry.AxisError(fitted.RaDeg, fitted.DecDeg, Lat, Lon, T);

            Assert.That(altErr, Is.EqualTo(offArcmin - PolarAlignGeometry.BennettRefractionArcmin(Lat)).Within(0.05));
            Assert.That(azErr, Is.EqualTo(0).Within(0.05));
        }

        [Test]
        public void AxisError_rejects_an_equatorial_site() {
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.AxisError(0, 90, 0, 0, T),
                "the celestial pole sits on the horizon at the equator — no alt/az decomposition");
        }

        // #1591 — how well does the two-point fit hold up when the seed sits close to the pole? The mount
        // axis is axisOffsetDeg off the pole; the camera sits (90° − seedDec) from the MOUNT axis (that is
        // what the mount's Dec reads); the mount turns 30° (RA increasing) about its axis; each solve
        // carries 10″ of tangent-plane noise per component. 300 seeded trials, camera azimuth varied.
        [SuppressMessage("Security", "CA5394:Do not use insecure randomness",
            Justification = "Seeded System.Random makes the synthetic solve noise deterministic; test-only, nothing security related.")]
        private static (System.Collections.Generic.List<double> ErrorsArcmin, int Rejected) FitErrorsArcmin(
                double axisOffsetDeg, double seedDec, bool knownDirection) {
            const int Trials = 300;
            const double RotationDeg = 30.0;
            const double NoiseArcsec = 10.0;
            var rng = new Random(1591);
            double Gauss() => Math.Sqrt(-2 * Math.Log(1 - rng.NextDouble())) * Math.Cos(2 * Math.PI * rng.NextDouble());
            var axis = Unit(40.0, 90.0 - axisOffsetDeg);
            var u = Unit(130.0, 0.0);
            var dotAU = axis.X * u.X + axis.Y * u.Y + axis.Z * u.Z;
            u = (u.X - dotAU * axis.X, u.Y - dotAU * axis.Y, u.Z - dotAU * axis.Z);
            var uLen = Math.Sqrt(u.X * u.X + u.Y * u.Y + u.Z * u.Z);
            u = (u.X / uLen, u.Y / uLen, u.Z / uLen);
            var theta = (90.0 - seedDec) * Math.PI / 180.0;

            (double X, double Y, double Z) Noisy((double X, double Y, double Z) v) {
                var e1 = Cross(v, (1.0, 0.0, 0.0));
                var e1Len = Math.Sqrt(e1.X * e1.X + e1.Y * e1.Y + e1.Z * e1.Z);
                e1 = (e1.X / e1Len, e1.Y / e1Len, e1.Z / e1Len);
                var e2 = Cross(v, e1);
                var sigma = NoiseArcsec / 3600.0 * Math.PI / 180.0;
                var n1 = Gauss() * sigma;
                var n2 = Gauss() * sigma;
                var w = (X: v.X + n1 * e1.X + n2 * e2.X, Y: v.Y + n1 * e1.Y + n2 * e2.Y, Z: v.Z + n1 * e1.Z + n2 * e2.Z);
                var wLen = Math.Sqrt(w.X * w.X + w.Y * w.Y + w.Z * w.Z);
                return (w.X / wLen, w.Y / wLen, w.Z / wLen);
            }

            var errorsArcmin = new System.Collections.Generic.List<double>();
            var rejected = 0;
            for (var i = 0; i < Trials; i++) {
                var tilted = Rotate(u, axis, 360.0 * i / Trials);
                var p1 = (X: axis.X * Math.Cos(theta) + tilted.X * Math.Sin(theta),
                          Y: axis.Y * Math.Cos(theta) + tilted.Y * Math.Sin(theta),
                          Z: axis.Z * Math.Cos(theta) + tilted.Z * Math.Sin(theta));
                var p2 = Rotate(p1, axis, RotationDeg);
                var (ra1, dec1) = RaDec(Noisy(p1));
                var (ra2, dec2) = RaDec(Noisy(p2));
                try {
                    var fitted = PolarAlignGeometry.FitAxisTwoPoint(ra1, dec1, ra2, dec2, RotationDeg, northernHemisphere: true,
                        raIncreasing: knownDirection ? true : null);
                    var f = Unit(fitted.RaDeg, fitted.DecDeg);
                    var cos = f.X * axis.X + f.Y * axis.Y + f.Z * axis.Z;
                    errorsArcmin.Add(Math.Acos(Math.Clamp(cos, -1, 1)) * 180.0 / Math.PI * 60.0);
                } catch (ArgumentOutOfRangeException) {
                    rejected++;
                }
            }
            errorsArcmin.Sort();
            return (errorsArcmin, rejected);
        }

        // Evidence only (no direction): the two axis lines the pointings admit are mirror images through the
        // pointing plane; the pole-nearest pick takes the wrong one whenever the mirror sits nearer the
        // pole, which happens as soon as the seed is not far from the pole compared with the axis offset.
        // The numbers are in the commit body for #1591.
        [TestCase(1.0, 80.0)]
        [TestCase(1.0, 85.0)]
        [TestCase(1.0, 87.0)]
        [TestCase(1.0, 88.0)]
        [TestCase(1.0, 89.0)]
        [TestCase(4.6, 80.0)]
        [TestCase(4.6, 85.0)]
        [TestCase(4.6, 87.0)]
        [TestCase(4.6, 88.0)]
        [TestCase(4.6, 89.0)]
        [TestCase(10.0, 80.0)]
        [TestCase(10.0, 85.0)]
        [TestCase(10.0, 87.0)]
        [TestCase(10.0, 88.0)]
        [TestCase(10.0, 89.0)]
        public void Two_point_fit_without_the_slew_direction_report(double axisOffsetDeg, double seedDec) {
            var (errors, rejected) = FitErrorsArcmin(axisOffsetDeg, seedDec, knownDirection: false);
            TestContext.Out.WriteLine(
                $"no direction: axisOffset {axisOffsetDeg} seedDec {seedDec}: rejected {rejected}, " +
                $"over 10 arcmin {errors.Count(e => e > 10.0)}/{errors.Count}, " +
                $"median {errors[errors.Count / 2]:F2}, p95 {errors[(int)(errors.Count * 0.95)]:F2}, max {errors[^1]:F2}");
            Assert.That(rejected, Is.Zero);
        }

        // With the mount's own turn direction the mirror line reproduces the turn the wrong way round and
        // is rejected: the fit stays on the true axis (solve noise only) at every seed Dec and axis offset.
        [TestCase(1.0, 80.0)]
        [TestCase(1.0, 85.0)]
        [TestCase(1.0, 87.0)]
        [TestCase(1.0, 88.0)]
        [TestCase(1.0, 89.0)]
        [TestCase(4.6, 80.0)]
        [TestCase(4.6, 85.0)]
        [TestCase(4.6, 87.0)]
        [TestCase(4.6, 88.0)]
        [TestCase(4.6, 89.0)]
        [TestCase(10.0, 80.0)]
        [TestCase(10.0, 85.0)]
        [TestCase(10.0, 87.0)]
        [TestCase(10.0, 88.0)]
        [TestCase(10.0, 89.0)]
        public void Two_point_fit_with_the_slew_direction_stays_on_the_true_axis(double axisOffsetDeg, double seedDec) {
            var (errors, rejected) = FitErrorsArcmin(axisOffsetDeg, seedDec, knownDirection: true);
            TestContext.Out.WriteLine(
                $"direction: axisOffset {axisOffsetDeg} seedDec {seedDec}: rejected {rejected}, " +
                $"median {errors[errors.Count / 2]:F2}, p95 {errors[(int)(errors.Count * 0.95)]:F2}, max {errors[^1]:F2}");
            Assert.That(rejected, Is.Zero);
            Assert.That(errors[^1], Is.LessThan(3.0), "arcmin; 10 arcsec of solve noise is ~0.6 arcmin median");
        }

        // ── three-point fit (the check stage) ──────────────────────────────────────────────

        private static double SeparationDeg((double RaDeg, double DecDeg) a, (double X, double Y, double Z) b) {
            var u = Unit(a.RaDeg, a.DecDeg);
            return Math.Acos(Math.Clamp(u.X * b.X + u.Y * b.Y + u.Z * b.Z, -1, 1)) * 180.0 / Math.PI;
        }

        private static void AssertThreePointRecovers(double axisRa, double axisDec, double pointRa, double pointDec,
                double stepDeg, bool north) {
            var axis = Unit(axisRa, axisDec);
            var p1 = Unit(pointRa, pointDec);
            var p2 = Rotate(p1, axis, stepDeg);
            var p3 = Rotate(p2, axis, stepDeg);
            var (ra1, dec1) = RaDec(p1);
            var (ra2, dec2) = RaDec(p2);
            var (ra3, dec3) = RaDec(p3);

            var fitted = PolarAlignGeometry.FitAxisThreePoint(ra1, dec1, ra2, dec2, ra3, dec3, north);

            Assert.That(SeparationDeg((fitted.RaDeg, fitted.DecDeg), axis), Is.LessThan(1e-6),
                $"axis ({axisRa},{axisDec}) step={stepDeg}° must be recovered exactly from noise-free pointings");
            var expectedCone = Math.Acos(Math.Clamp(p1.X * axis.X + p1.Y * axis.Y + p1.Z * axis.Z, -1, 1)) * 180.0 / Math.PI;
            Assert.That(fitted.ConeHalfAngleDeg, Is.EqualTo(expectedCone).Within(1e-6));
            // The solved turn about the fitted axis is the step the generator used (RA up = positive).
            var turn = PolarAlignGeometry.TurnAboutAxisDeg(fitted.RaDeg, fitted.DecDeg, ra1, dec1, ra2, dec2);
            Assert.That(Math.Abs(turn), Is.EqualTo(Math.Abs(stepDeg)).Within(1e-6));
        }

        [Test]
        public void Three_point_fit_recovers_a_known_axis_without_the_rotation() {
            // The check's own geometry: Dec 85° from Home, two 30° turns.
            AssertThreePointRecovers(axisRa: 30, axisDec: 89.5, pointRa: 100, pointDec: 85, stepDeg: 30, north: true);
            // A rougher axis, smaller and larger steps, a pointing further out.
            AssertThreePointRecovers(210, 88.0, 350, 85, 15, true);
            AssertThreePointRecovers(210, 88.0, 350, 60, 45, true);
            // Southern hemisphere: the end nearer the SCP is returned.
            AssertThreePointRecovers(120, -89.3, 40, -85, 30, north: false);
        }

        [Test]
        public void Three_point_fit_has_no_mirror_ambiguity_near_the_pole() {
            // #1591's regime for the two-point fit: a seed close to the pole picked the mirror
            // line. Three points fix the circle, so the direction of the turn is not needed.
            AssertThreePointRecovers(axisRa: 0, axisDec: 89.9, pointRa: 180, pointDec: 85, stepDeg: 30, north: true);
            AssertThreePointRecovers(0, 89.9, 180, 85, -30, true); // turned the other way
        }

        [Test]
        public void Three_point_fit_refuses_coincident_pointings() {
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.FitAxisThreePoint(10, 85, 10, 85, 40, 85, true), "two coincident pointings");
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.FitAxisThreePoint(10, 85, 40, 85, 40, 85, true), "the last two coincide");
        }

        [Test]
        public void Three_point_fit_reads_points_on_the_equator_as_an_axis_on_the_pole() {
            // Three distinct points on a sphere always lie on one circle; on the equator that
            // circle's pole is the celestial pole itself — a perfectly aligned axis, not a failure.
            var fitted = PolarAlignGeometry.FitAxisThreePoint(0, 0, 10, 0, 20, 0, true);
            Assert.That(fitted.DecDeg, Is.EqualTo(90.0).Within(1e-9));
            Assert.That(fitted.ConeHalfAngleDeg, Is.EqualTo(90.0).Within(1e-9));
        }

        [Test]
        public void Three_point_fit_refuses_an_axis_far_from_the_target_pole() {
            // A mount pointed 40° from the pole: the §45 rough-alignment precondition fails.
            var axis = Unit(0, 50);
            var p1 = Unit(90, 20);
            var p2 = Rotate(p1, axis, 30);
            var p3 = Rotate(p2, axis, 30);
            var (ra1, dec1) = RaDec(p1);
            var (ra2, dec2) = RaDec(p2);
            var (ra3, dec3) = RaDec(p3);
            Assert.Throws<ArgumentOutOfRangeException>(() =>
                PolarAlignGeometry.FitAxisThreePoint(ra1, dec1, ra2, dec2, ra3, dec3, true));
        }

        [Test]
        [System.Diagnostics.CodeAnalysis.SuppressMessage("Security", "CA5394:Do not use insecure randomness",
            Justification = "Seeded System.Random makes the synthetic solve noise deterministic; test-only, nothing security related.")]
        public void Three_point_fit_tolerates_solve_noise_at_the_checks_geometry() {
            // 10″ of per-solve scatter at Dec 85° with 30° steps: the error must stay within the
            // "excellent" band's resolution (a few arcminutes at worst, mostly under one).
            var rng = new Random(7);
            var axis = Unit(30, 89.5);
            var worst = 0.0;
            for (var i = 0; i < 200; i++) {
                var p1 = Unit(100 + i, 85);
                var p2 = Rotate(p1, axis, 30);
                var p3 = Rotate(p2, axis, 30);
                (double, double) Noisy((double X, double Y, double Z) p) {
                    var (ra, dec) = RaDec(p);
                    var noise = 10.0 / 3600.0;
                    return (ra + (rng.NextDouble() - 0.5) * 2 * noise / Math.Cos(dec * Math.PI / 180), dec + (rng.NextDouble() - 0.5) * 2 * noise);
                }
                var (ra1, dec1) = Noisy(p1);
                var (ra2, dec2) = Noisy(p2);
                var (ra3, dec3) = Noisy(p3);
                var fitted = PolarAlignGeometry.FitAxisThreePoint(ra1, dec1, ra2, dec2, ra3, dec3, true);
                worst = Math.Max(worst, SeparationDeg((fitted.RaDeg, fitted.DecDeg), axis) * 60.0);
            }
            Assert.That(worst, Is.LessThan(3.0), "arcmin");
        }
