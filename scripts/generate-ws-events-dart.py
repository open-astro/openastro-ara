#!/usr/bin/env python3
"""Generate the Dart WebSocket event names and typed payload classes from the committed daemon snapshot (ADR 0014).

Reads OpenAstroAra.Server/ws-events.json and writes
client/openastroara_client/lib/models/ws_event_types.dart.
`--check` exits 1 when the committed Dart file differs (scripts/tests/test_generate_ws_events_dart.py runs it in CI).
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "OpenAstroAra.Server" / "ws-events.json"
OUT = ROOT / "client" / "openastroara_client" / "lib" / "models" / "ws_event_types.dart"


def camel(snake: str) -> str:
    head, *rest = snake.split("_")
    return head + "".join(w.capitalize() for w in rest)


DART_TYPES = {"string": "String", "boolean": "bool", "number": "double", "integer": "int"}


def render_payload(event: dict) -> list:
    """One immutable class with a strict fromJson for an event that carries a payload shape."""
    cls = event["name"] + "Payload"
    fields = event["payload"]
    out = [
        "",
        f"/// Payload of `{event['type']}`; a missing or mistyped field throws a [TypeError].",
        f"final class {cls} {{",
        f"  const {cls}({{",
    ]
    out += [f"    {'' if f['nullable'] else 'required '}this.{camel(f['field'])}," for f in fields]
    out += ["  });", "", f"  factory {cls}.fromJson(Map<String, dynamic> json) =>", f"      {cls}("]
    for f in fields:
        key, q = f"json['{f['field']}']", "?" if f["nullable"] else ""
        if f["type"] == "number":
            expr = f"({key} as num{q}){q}.toDouble()"
        else:
            expr = f"{key} as {DART_TYPES[f['type']]}{q}"
        out.append(f"        {camel(f['field'])}: {expr},")
    out += ["      );", ""]
    out += [f"  final {DART_TYPES[f['type']]}{'?' if f['nullable'] else ''} {camel(f['field'])};" for f in fields]
    out.append("}")
    return out


def render(snapshot_text: str) -> str:
    events = json.loads(snapshot_text)["events"]
    lines = [
        "// GENERATED by scripts/generate-ws-events-dart.py from OpenAstroAra.Server/ws-events.json; do not hand-edit.",
        "// Declared once in the daemon (WsEventCatalog, ADR 0014); refresh the snapshot first, then rerun the script.",
        "",
        "/// Wire tokens of every WebSocket event the daemon declares.",
        "abstract final class WsEventTypes {",
    ]
    for e in events:
        name = e["name"][0].lower() + e["name"][1:]
        line = f"  static const String {name} = '{e['type']}';"
        # dart format wraps a declaration past 80 columns; emit that shape so the file stays formatted.
        lines.extend([f"  static const String {name} =", f"      '{e['type']}';"] if len(line) > 80 else [line])
    lines.append("}")
    for e in events:
        if "payload" in e:
            lines += render_payload(e)
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    text = render(SNAPSHOT.read_text(encoding="utf-8"))
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} drifted from {SNAPSHOT.relative_to(ROOT)}; run scripts/generate-ws-events-dart.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
